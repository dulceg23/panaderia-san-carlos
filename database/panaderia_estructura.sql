    PROCEDURE CREAR_SESION (

        P_ID_USUARIO IN NUMBER,

        P_TOKEN OUT VARCHAR2

    )

    IS

        V_EXISTE NUMBER;

    BEGIN


        SELECT COUNT(*)

        INTO V_EXISTE

        FROM USUARIO

        WHERE ID_USUARIO = P_ID_USUARIO

        AND ESTADO = 'ACTIVO';


        IF V_EXISTE = 0 THEN

            RAISE_APPLICATION_ERROR(
                -20092,
                'No se puede crear una sesión para este usuario.'
            );

        END IF;


        /* CERRAR SESIONES ANTERIORES */

        UPDATE SESION_USUARIO

        SET ESTADO = 'CERRADA'

        WHERE ID_USUARIO = P_ID_USUARIO

        AND ESTADO = 'ACTIVA';


        /* GENERAR TOKEN */

        SELECT
            RAWTOHEX(SYS_GUID())
            ||
            RAWTOHEX(SYS_GUID())

        INTO P_TOKEN

        FROM DUAL;


        /* REGISTRAR NUEVA SESION */

        INSERT INTO SESION_USUARIO (

            ID_SESION,

            ID_USUARIO,

            TOKEN,

            FECHA_CREACION,

            FECHA_EXPIRACION,

            ESTADO

        )
        VALUES (

            SEQ_SESION_USUARIO.NEXTVAL,

            P_ID_USUARIO,

            P_TOKEN,

            SYSDATE,

            SYSDATE + (8 / 24),

            'ACTIVA'
        );


        COMMIT;


    EXCEPTION

        WHEN OTHERS THEN

            ROLLBACK;

            RAISE;

    END CREAR_SESION;
