    BEGIN
        IF P_CANTIDAD <= 0 THEN
            RAISE_APPLICATION_ERROR(-20043,
                'LA CANTIDAD A PRODUCIR DEBE SER MAYOR QUE CERO');
        END IF;

        -- Validar que sea un producto final activo.
        SELECT COUNT(*)
        INTO V_PRODUCTO_FINAL
        FROM PRODUCTO
        WHERE ID_PRODUCTO = P_ID_PRODUCTO
          AND ID_TIPO_PRODUCTO = 1
          AND ESTADO = 1;

        IF V_PRODUCTO_FINAL = 0 THEN
            RAISE_APPLICATION_ERROR(-20044,
                'EL PRODUCTO NO EXISTE, ESTA INACTIVO O NO ES PRODUCTO FINAL');
        END IF;

        -- Validar que tenga receta activa.
        BEGIN
            SELECT ID_RECETA
            INTO V_ID_RECETA
            FROM RECETA
            WHERE ID_PRODUCTO_FINAL = P_ID_PRODUCTO
              AND ESTADO = 1;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20045,
                    'EL PRODUCTO FINAL NO TIENE UNA RECETA ACTIVA');
        END;

        -- Validar que la receta tenga ingredientes.
        SELECT COUNT(*)
        INTO V_CANT_ING
        FROM DETALLE_RECETA
        WHERE ID_RECETA = V_ID_RECETA;

        IF V_CANT_ING = 0 THEN
            RAISE_APPLICATION_ERROR(-20046,
                'LA RECETA NO TIENE INGREDIENTES');
        END IF;

        -- Validar que el inventario del producto final exista.
        BEGIN
            SELECT EXISTENCIA
            INTO V_INV_FINAL
            FROM INVENTARIO
            WHERE ID_PRODUCTO = P_ID_PRODUCTO
            FOR UPDATE;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20047,
                    'EL PRODUCTO FINAL NO TIENE INVENTARIO REGISTRADO');
        END;

        -- Bloquear y validar existencias de todos los insumos.
        FOR R IN (
            SELECT ID_INSUMO, CANTIDAD
            FROM DETALLE_RECETA
            WHERE ID_RECETA = V_ID_RECETA
            ORDER BY ID_INSUMO
        )
        LOOP
            BEGIN
                SELECT EXISTENCIA
                INTO V_EXISTENCIA
                FROM INVENTARIO
                WHERE ID_PRODUCTO = R.ID_INSUMO
                FOR UPDATE;
            EXCEPTION
                WHEN NO_DATA_FOUND THEN
                    RAISE_APPLICATION_ERROR(-20048,
                        'UN INSUMO DE LA RECETA NO TIENE INVENTARIO REGISTRADO');
            END;

            V_NECESARIO := R.CANTIDAD * P_CANTIDAD;

            IF V_EXISTENCIA < V_NECESARIO THEN
                RAISE_APPLICATION_ERROR(
                    -20049,
                    'NO HAY SUFICIENTE INVENTARIO PARA REALIZAR LA PRODUCCION'
                );
            END IF;
        END LOOP;

        -- Crear cabecera de produccion.
        SELECT SEQ_PRODUCCION.NEXTVAL
        INTO P_ID_PRODUCCION
        FROM DUAL;

        INSERT INTO PRODUCCION (
            ID_PRODUCCION,
            FECHA,
            ESTADO
        )
        VALUES (
            P_ID_PRODUCCION,
            SYSDATE,
            'REGISTRADA'
        );

        -- Registrar producto producido.
        INSERT INTO DETALLE_PRODUCCION (
            ID_DETALLE_PRODUCCION,
            ID_PRODUCCION,
            ID_PRODUCTO,
            CANTIDAD
        )
        VALUES (
            SEQ_DETALLE_PRODUCCION.NEXTVAL,
            P_ID_PRODUCCION,
            P_ID_PRODUCTO,
            P_CANTIDAD
        );

        -- Descontar insumos y registrar movimientos de salida.
        FOR R IN (
            SELECT ID_INSUMO, CANTIDAD
            FROM DETALLE_RECETA
            WHERE ID_RECETA = V_ID_RECETA
            ORDER BY ID_INSUMO
        )
        LOOP
            V_NECESARIO := R.CANTIDAD * P_CANTIDAD;

            UPDATE INVENTARIO
            SET EXISTENCIA = EXISTENCIA - V_NECESARIO
            WHERE ID_PRODUCTO = R.ID_INSUMO;

            INSERT INTO MOVIMIENTO_INVENTARIO (
                ID_MOVIMIENTO,
                ID_PRODUCTO,
                FECHA,
                TIPO_MOVIMIENTO,
                CANTIDAD,
                DESCRIPCION
            )
            VALUES (
                SEQ_MOVIMIENTO.NEXTVAL,
                R.ID_INSUMO,
                SYSDATE,
                'SALIDA',
                V_NECESARIO,
                'CONSUMO POR PRODUCCION #' || P_ID_PRODUCCION
            );
        END LOOP;

        -- Aumentar inventario del producto final.
        UPDATE INVENTARIO
        SET EXISTENCIA = EXISTENCIA + P_CANTIDAD
        WHERE ID_PRODUCTO = P_ID_PRODUCTO;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20050,
                'NO SE PUDO ACTUALIZAR EL INVENTARIO DEL PRODUCTO FINAL');
        END IF;

        INSERT INTO MOVIMIENTO_INVENTARIO (
            ID_MOVIMIENTO,
            ID_PRODUCTO,
            FECHA,
            TIPO_MOVIMIENTO,
            CANTIDAD,
            DESCRIPCION
        )
        VALUES (
            SEQ_MOVIMIENTO.NEXTVAL,
            P_ID_PRODUCTO,
            SYSDATE,
            'ENTRADA',
            P_CANTIDAD,
            'PRODUCCION TERMINADA #' || P_ID_PRODUCCION
        );

        COMMIT;

    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END REGISTRAR_PRODUCCION;

END PKG_INVENTARIO_PRODUCCION;
