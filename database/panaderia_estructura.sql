  CREATE OR REPLACE EDITIONABLE PACKAGE BODY "PKG_INVENTARIO_PRODUCCION" AS

    PROCEDURE ENTRADA_INVENTARIO (
        P_ID_PRODUCTO IN NUMBER,
        P_CANTIDAD    IN NUMBER,
        P_DESCRIPCION IN VARCHAR2
    )
    AS
        V_PRODUCTO NUMBER;
    BEGIN
        IF P_CANTIDAD <= 0 THEN
            RAISE_APPLICATION_ERROR(-20040,
                'LA CANTIDAD DEBE SER MAYOR QUE CERO');
        END IF;

        SELECT COUNT(*)
        INTO V_PRODUCTO
        FROM PRODUCTO
        WHERE ID_PRODUCTO = P_ID_PRODUCTO
          AND ESTADO = 1;

        IF V_PRODUCTO = 0 THEN
            RAISE_APPLICATION_ERROR(-20041,
                'EL PRODUCTO NO EXISTE O ESTA INACTIVO');
        END IF;

        UPDATE INVENTARIO
        SET EXISTENCIA = EXISTENCIA + P_CANTIDAD
        WHERE ID_PRODUCTO = P_ID_PRODUCTO;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20042,
                'EL PRODUCTO NO TIENE INVENTARIO REGISTRADO');
        END IF;

        INSERT INTO MOVIMIENTO_INVENTARIO (
            ID_MOVIMIENTO,
            ID_PRODUCTO,
            FECHA,
            TIPO_MOVIMIENTO,
            CANTIDAD,
            DESCRIPCION
        )
        VALUES (
            SEQ_MOVIMIENTO.NEXTVAL,
            P_ID_PRODUCTO,
            SYSDATE,
            'ENTRADA',
            P_CANTIDAD,
            NVL(P_DESCRIPCION, 'ENTRADA DE INVENTARIO')
        );

        COMMIT;

    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END ENTRADA_INVENTARIO;


    PROCEDURE REGISTRAR_PRODUCCION (
