    PROCEDURE VALIDAR_SESION (

        P_TOKEN IN VARCHAR2,

        P_ID_USUARIO OUT NUMBER,

        P_NOMBRE_COMPLETO OUT VARCHAR2,

        P_ID_ROL OUT NUMBER,

        P_ROL OUT VARCHAR2,

        P_ID_SUCURSAL OUT NUMBER

    )

    IS

        V_ID_SESION NUMBER;

        V_FECHA_EXPIRACION DATE;

    BEGIN


        BEGIN

            SELECT

                SE.ID_SESION,

                SE.FECHA_EXPIRACION,

                U.ID_USUARIO,

                U.NOMBRE_COMPLETO,

                U.ID_ROL,

                R.NOMBRE,

                U.ID_SUCURSAL

            INTO

                V_ID_SESION,

                V_FECHA_EXPIRACION,

                P_ID_USUARIO,

                P_NOMBRE_COMPLETO,

                P_ID_ROL,

                P_ROL,

                P_ID_SUCURSAL

            FROM SESION_USUARIO SE

            INNER JOIN USUARIO U
                ON U.ID_USUARIO = SE.ID_USUARIO

            INNER JOIN ROL R
                ON R.ID_ROL = U.ID_ROL

            WHERE SE.TOKEN = P_TOKEN

            AND SE.ESTADO = 'ACTIVA'

            AND U.ESTADO = 'ACTIVO'

            AND R.ESTADO = 'ACTIVO';


        EXCEPTION

            WHEN NO_DATA_FOUND THEN

                RAISE_APPLICATION_ERROR(
                    -20093,
                    'La sesión no es válida.'
                );

        END;


        IF V_FECHA_EXPIRACION <= SYSDATE THEN

            UPDATE SESION_USUARIO

            SET ESTADO = 'EXPIRADA'

            WHERE ID_SESION = V_ID_SESION;


            COMMIT;


            RAISE_APPLICATION_ERROR(
                -20094,
                'La sesión ha expirado.'
            );

        END IF;


